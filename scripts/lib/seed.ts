/** Shared by scripts/build-seed.ts and the test setup (vitest.config.ts). Node-only. */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export interface HolidayFile {
  year: number;
  data_version: string;
  updated_at: string;
  decrees: { ref: string; url: string }[];
  revisions?: { version: string; date: string; notes: string }[];
  notes?: string;
  entries: {
    date: string;
    name_id: string;
    name_en: string;
    type: "national" | "cuti_bersama";
    source_ref?: string;
    source_url?: string;
  }[];
}

// `type` (not interface) so it is assignable to miniflare's Json binding type.
export type SeedYear = {
  version: { version: string; year: number; source_ref: string; source_url: string; updated_at: string; notes: string | null };
  holidays: { date: string; year: number; name_id: string; name_en: string; type: string; source_ref: string; source_url: string; data_version: string }[];
};

function fail(file: string, msg: string): never {
  throw new Error(`${file}: ${msg}`);
}

const isDate = (s: unknown): s is string =>
  typeof s === "string" && /^\d{4}-\d{2}-\d{2}$/.test(s) && new Date(`${s}T00:00:00Z`).toISOString().startsWith(s);
const isStr = (s: unknown): s is string => typeof s === "string" && s.trim().length > 0;

export function validate(file: string, f: HolidayFile): SeedYear {
  if (!Number.isInteger(f.year)) fail(file, "'year' must be an integer");
  if (!file.endsWith(`${f.year}.json`)) fail(file, `file name must be ${f.year}.json`);
  if (!isStr(f.data_version)) fail(file, "'data_version' is required");
  if (!isStr(f.updated_at) || Number.isNaN(Date.parse(f.updated_at))) fail(file, "'updated_at' must be an ISO timestamp");
  if (!Array.isArray(f.decrees) || f.decrees.length === 0) fail(file, "'decrees' must be a non-empty array");
  f.decrees.forEach((d, i) => (isStr(d.ref) && isStr(d.url)) || fail(file, `decrees[${i}] needs ref and url`));
  if (!Array.isArray(f.entries)) fail(file, "'entries' must be an array");
  const seen = new Set<string>();
  const holidays = f.entries.map((e, i) => {
    const at = `entries[${i}]`;
    if (!isDate(e.date) || !e.date.startsWith(`${f.year}-`)) fail(file, `${at}.date must be a valid date in ${f.year}`);
    if (!isStr(e.name_id) || !isStr(e.name_en)) fail(file, `${at} needs name_id and name_en`);
    if (e.type !== "national" && e.type !== "cuti_bersama") fail(file, `${at}.type must be national|cuti_bersama`);
    const key = `${e.date}|${e.type}|${e.name_id}`;
    if (seen.has(key)) fail(file, `${at} duplicates an earlier entry`);
    seen.add(key);
    return {
      date: e.date,
      year: f.year,
      name_id: e.name_id,
      name_en: e.name_en,
      type: e.type,
      source_ref: e.source_ref ?? f.decrees[0]!.ref,
      source_url: e.source_url ?? f.decrees[0]!.url,
      data_version: f.data_version,
    };
  });
  const latestRevision = f.revisions?.at(-1);
  return {
    version: {
      version: f.data_version,
      year: f.year,
      source_ref: f.decrees.map((d) => d.ref).join("; "),
      source_url: f.decrees.map((d) => d.url).join(" "),
      updated_at: f.updated_at,
      notes: f.notes ?? latestRevision?.notes ?? null,
    },
    holidays,
  };
}

export function loadSeedYears(dir: string): SeedYear[] {
  return readdirSync(dir)
    .filter((n) => /^\d{4}\.json$/.test(n))
    .sort()
    .map((n) => validate(n, JSON.parse(readFileSync(join(dir, n), "utf8")) as HolidayFile));
}

const q = (v: string | number | null) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replaceAll("'", "''")}'`);

/** Idempotent SQL: for each year, wipe and re-insert. */
export function toSql(years: SeedYear[]): string {
  const out = ["-- GENERATED by scripts/build-seed.ts from data/holidays/*.json. Do not edit."];
  for (const { version: v, holidays } of years) {
    out.push(`\n-- ${v.year} (${v.version})`);
    out.push(`DELETE FROM holidays WHERE year = ${v.year};`);
    out.push(`DELETE FROM data_versions WHERE year = ${v.year};`);
    out.push(
      `INSERT INTO data_versions (version, year, source_ref, source_url, updated_at, notes) VALUES (${[v.version, v.year, v.source_ref, v.source_url, v.updated_at, v.notes].map(q).join(", ")});`,
    );
    for (const h of holidays) {
      out.push(
        `INSERT INTO holidays (date, year, name_id, name_en, type, source_ref, source_url, data_version) VALUES (${[h.date, h.year, h.name_id, h.name_en, h.type, h.source_ref, h.source_url, h.data_version].map(q).join(", ")});`,
      );
    }
  }
  return out.join("\n") + "\n";
}
